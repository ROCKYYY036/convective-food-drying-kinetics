import numpy as np
import pandas as pd
from scipy.optimize import curve_fit


def newton(t,k):
  return np.exp(-k *t)

def page(t, k, n):
  return np.exp(-k * t**n)

def hp(t, a, k):
  return a* np.exp(-k *t)

#fit models
p_newton, _ = curve_fit(
    newton, t, MR, p0=[0.01], bounds=(0, np.inf)
)

p_page, _ = curve_fit(
    page, t, MR, p0=[0.01,1.0],
    bounds=(0,np.inf), maxfev=10000
)

p_hp, _ = curve_fit(
    hp, t, MR, p0=[1.0, 0.01],
    bounds=([0, 0], [np.inf, np.inf]),
    maxfev=10000
)

#prediction
predictions ={
    "Newton": newton(t, *p_newton),
    "page": page(t, *p_page),
    "Henderson-Pabis": hp(t, *p_hp)
}
#calculate matrics
results= []


for model_name, pred in predictions.items():
  error = pred - MR


rmse = np.sqrt(np.mean(error**2))
r2 = 1- np.sum(error**2) / np.sum((MR - np.mean(MR))**2)

results.append({
    "model": model_name,
    "RMSE": rmse,
    "R2": r2
})
comparison = pd.DataFrame(results)
