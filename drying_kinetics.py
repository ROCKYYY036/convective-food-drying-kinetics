import numpy as np
import pandas as pd

models = {
    "Newton": (newton(t, *p_newton), 1),
    "Page": (page(t, *p_page), 2),
    "Henderson-Pabis": (hp(t, *p_hp), 2)
}

results = []

N = len(MR)

for name, (prediction, parameters_count) in models.items():

    residual = MR - prediction
    SSE = np.sum(residual**2)

    RMSE_model = np.sqrt(SSE / N)
    R2_model = 1 - SSE / np.sum((MR - np.mean(MR))**2)

    AIC = N * np.log(SSE / N) + 2 * parameters_count

    results.append({
        "Model": name,
        "Parameters": parameters_count,
        "RMSE": RMSE_model,
        "R2": R2_model,
        "AIC": AIC
    })

comparison = pd.DataFrame(results)

print(comparison.round(6).to_string(index=False))

