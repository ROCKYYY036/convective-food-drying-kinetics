#Newton Model
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
from scipy.optimize import curve_fit

# load experimental data
df = pd.read_csv("experimental_data.csv")

# experimental data
t = df["time_min"].to_numpy()
MR = df["moisture_ratio_M_over_M0"].to_numpy()

# newton mathematical model
def newton_model(t, k):
    return np.exp(-k * t)

# estimate the drying constant
parameters, covariance = curve_fit(
    newton_model,
    t,
    MR,
    p0=[0.01],
    bounds=(0, np.inf)
)
k = parameters[0]

# calculate model prediction
predicted_MR = newton_model(t, k)

# calculate evaluation metrics
residuals = MR - predicted_MR
RMSE = np.sqrt(np.mean(residuals**2))

SS_res = np.sum(residuals**2)
SS_tot = np.sum((MR - np.mean(MR))**2)
R2 = 1 - SS_res / SS_tot

# display result
print("newton drying constant:", k, "min^-1")
print("RMSE:", RMSE)
print("R-squared:", R2)

# plot experimental data and model
plt.figure(figsize=(8, 5))
plt.scatter(t, MR, label="Experimental data")
plt.plot(t, predicted_MR, label="Newton model")

plt.xlabel("drying time(min)")
plt.ylabel("Moisture Ratio")
plt.title("Newton Model - Apple Drying at 50degC")

plt.grid(True)
plt.legend()
plt.show()

